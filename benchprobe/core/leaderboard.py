"""Leaderboard schema and JSON store.

The leaderboard is a single JSON file under ``leaderboard/data.json``. It is
the source of truth for the static site and the API consumers. Schema is
intentionally tiny — anything richer (commit history, severity trends) lives
in derived files generated by ``leaderboard/render.py``.
"""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from benchprobe.core.verdict import Verdict, VerdictKind


class LeaderboardEntry(BaseModel):
    """One row in ``leaderboard/data.json`` — one benchmark, one audit run."""

    model_config = ConfigDict(frozen=True)

    benchmark: str
    version_sha: str
    family_verdicts: dict[str, VerdictKind]
    audited_at: datetime
    auditor_version: str
    evidence_url: str | None = None

    @property
    def passing(self) -> bool:
        """A benchmark passes iff every family verdict is ``PASS``.

        Even one ``INCONCLUSIVE`` makes the row non-passing — the
        leaderboard's whole point is to not silently let unknowns through.
        """
        return all(v is VerdictKind.PASS for v in self.family_verdicts.values())

    @property
    def n_vulnerable(self) -> int:
        return sum(1 for v in self.family_verdicts.values() if v is VerdictKind.VULNERABLE)

    @property
    def n_inconclusive(self) -> int:
        return sum(1 for v in self.family_verdicts.values() if v is VerdictKind.INCONCLUSIVE)


def entry_from_verdicts(
    benchmark: str,
    version_sha: str,
    verdicts: list[Verdict],
    auditor_version: str = "0.1.0",
    evidence_url: str | None = None,
) -> LeaderboardEntry:
    """Collapse a list of per-family verdicts into one leaderboard row."""
    return LeaderboardEntry(
        benchmark=benchmark,
        version_sha=version_sha,
        family_verdicts={v.family: v.kind for v in verdicts},
        audited_at=datetime.now(UTC),
        auditor_version=auditor_version,
        evidence_url=evidence_url,
    )


class LeaderboardStore(BaseModel):
    """Read-modify-write wrapper around ``leaderboard/data.json``."""

    model_config = ConfigDict(frozen=False)

    entries: list[LeaderboardEntry] = Field(default_factory=list)
    schema_version: int = 1

    @classmethod
    def load(cls, path: Path) -> LeaderboardStore:
        if not path.exists():
            return cls()
        raw: Any = json.loads(path.read_text(encoding="utf-8"))
        return cls.model_validate(raw)

    def save(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.model_dump_json(indent=2), encoding="utf-8")

    def upsert(self, entry: LeaderboardEntry) -> bool:
        """Insert or replace the row for ``entry.benchmark``.

        Returns ``True`` if the stored row changed (different verdicts or
        different SHA), ``False`` if the new entry matches the existing one.
        The sweep workflow uses the return value to decide whether to open a PR.
        """
        for i, existing in enumerate(self.entries):
            if existing.benchmark == entry.benchmark:
                changed = (
                    existing.version_sha != entry.version_sha
                    or existing.family_verdicts != entry.family_verdicts
                )
                self.entries[i] = entry
                return changed
        self.entries.append(entry)
        return True

    def get(self, benchmark: str) -> LeaderboardEntry | None:
        for entry in self.entries:
            if entry.benchmark == benchmark:
                return entry
        return None
